module alu(

    input  wire [7:0] a,
    input  wire [7:0] b,

    input  wire [3:0] op,

    output reg  [7:0] result,

    output wire zero,
    output wire carry,
    output wire overflow,
    output wire negative

);

reg carry_reg;
reg overflow_reg;

reg [8:0] temp;

always @(*) begin

    carry_reg = 0;
    overflow_reg = 0;
    temp = 9'd0;

    case(op)

    //-----------------------------------------
    // ADD
    //-----------------------------------------
    4'h0:
    begin
        temp = a + b;
        result = temp[7:0];
        carry_reg = temp[8];

        overflow_reg =
            (~a[7] & ~b[7] & result[7]) |
            ( a[7] &  b[7] & ~result[7]);
    end

    //-----------------------------------------
    // SUB
    //-----------------------------------------
    4'h1:
    begin
        temp = a - b;
        result = temp[7:0];
        carry_reg = temp[8];

        overflow_reg =
            (~a[7] & b[7] & result[7]) |
            ( a[7] & ~b[7] & ~result[7]);
    end

    //-----------------------------------------
    // AND
    //-----------------------------------------
    4'h2:
        result = a & b;

    //-----------------------------------------
    // OR
    //-----------------------------------------
    4'h3:
        result = a | b;

    //-----------------------------------------
    // XOR
    //-----------------------------------------
    4'h4:
        result = a ^ b;

    //-----------------------------------------
    // NOT
    //-----------------------------------------
    4'h5:
        result = ~a;

    //-----------------------------------------
    // SHL
    //-----------------------------------------
    4'h6:
    begin
        result = a << 1;
        carry_reg = a[7];
    end

    //-----------------------------------------
    // SHR
    //-----------------------------------------
    4'h7:
    begin
        result = a >> 1;
        carry_reg = a[0];
    end

    //-----------------------------------------
    // CMP
    //-----------------------------------------
    4'h8:
    begin
        temp = a - b;
        result = temp[7:0];
        carry_reg = temp[8];
    end

    //-----------------------------------------
    // PASS A
    //-----------------------------------------
    4'h9:
        result = a;

    //-----------------------------------------
    // PASS B
    //-----------------------------------------
    4'hA:
        result = b;

    //-----------------------------------------
    default:
        result = 8'h00;

    endcase

end